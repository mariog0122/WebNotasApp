export const getProvinces = () => ECUADOR_DATA.map(item => item.province)

export const getCantons = (provinceName) => {
  const found = ECUADOR_DATA.find(item => item.province === provinceName)
  return found ? found.cantons.map(c => c.name) : []
}

export const getParishes = (provinceName, cantonName) => {
  const foundProv = ECUADOR_DATA.find(item => item.province === provinceName)
  if (!foundProv) return []
  const foundCanton = foundProv.cantons.find(c => c.name === cantonName)
  return foundCanton ? foundCanton.parishes : []
}
